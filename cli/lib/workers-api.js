// Update without the game files (update-from-link). Cloudflare cannot hand
// back a Worker's static files, and `wrangler deploy` always replaces all of
// them, so the CLI patches the Worker's latest version through the Workers
// API instead: fields left out of a JSON Merge Patch, the static files among
// them, carry over to the new version. The only place the toolkit calls that
// API itself.
//
// (A script upload with `keep_assets: true` keeps the files too, but it also
// keeps the old asset routing, so the Worker never saw js/plugins.js.)

import fs from "node:fs";
import path from "node:path";
import { toolkitRoutes } from "../../worker/toolkit.js";
import { COMPATIBILITY_DATE, overflowRoutes, workerVars } from "./cloudflare.js";
import { log } from "./ui.js";

// What the requests below were written against. `checkWorkersApi()` checks it
// against Cloudflare's published OpenAPI schema (scripts/check-workers-api.js,
// run every week by .github/workflows/workers-api.yml); when that check
// fails, fix the requests and update `checked`.
export const WORKERS_API = {
  base: "https://api.cloudflare.com/client/v4",
  // GET: only to check that the Worker exists before changing it.
  worker: "/accounts/{account_id}/workers/workers/{worker_id}",
  // PATCH ?deploy=true: a new version from the latest one, at 100% of traffic.
  patchLatest: "/accounts/{account_id}/workers/workers/{worker_id}/versions/latest",
  // Fields sent: main_module, compatibility_date, bindings (plain_text,
  // r2_bucket, assets), modules (name, content_type, content_base64),
  // assets.config (not_found_handling, run_worker_first).
  schema: "https://raw.githubusercontent.com/cloudflare/api-schemas/main/openapi.json",
  checked: "2026-10-25",
};

// The same Worker as writeWorkerProject() + `wrangler deploy`, plus the newer
// toolkit for the Worker to serve (worker/toolkit.js). Modules go up
// unbundled: the API resolves their relative imports. -> merge patch body
export function keepAssetsPatch({ slug, gameId = slug, bucket, overflowRels, auth, toolkitRoot, indexable = false, saveHistory = false, toolkit }) {
  const vars = workerVars({ gameId, auth, locked: false, indexable, saveHistory });
  const bindings = Object.entries(vars).map(([name, text]) => ({ name, type: "plain_text", text }));
  if (bucket) bindings.push({ name: "BUCKET", type: "r2_bucket", bucket_name: bucket });
  bindings.push({ name: "ASSETS", type: "assets" });

  const modules = {
    "worker.js":
      `// Generated by rpgmaker-web-toolkit. Do not edit.\n` +
      `import { createWorker } from "./worker/index.js";\n` +
      `import overflow from "./rwk-overflow.js";\n` +
      `import toolkit from "./rwk-toolkit.js";\n` +
      `export default createWorker({ overflow, toolkit });\n`,
    "rwk-overflow.js": `export default ${JSON.stringify(overflowRels)};\n`,
    "rwk-toolkit.js": `export default ${JSON.stringify(toolkit)};\n`,
  };
  const workerDir = path.join(toolkitRoot, "worker");
  for (const name of fs.readdirSync(workerDir).filter((f) => f.endsWith(".js"))) {
    modules[`worker/${name}`] = fs.readFileSync(path.join(workerDir, name), "utf8");
  }

  return {
    main_module: "worker.js",
    compatibility_date: COMPATIBILITY_DATE,
    bindings,
    // Arrays are replaced as a whole by a merge patch: the old modules go.
    modules: Object.entries(modules).map(([name, source]) => ({
      name,
      content_type: "application/javascript+module",
      content_base64: Buffer.from(source, "utf8").toString("base64"),
    })),
    // No jwt: the files carry over.
    assets: { config: { not_found_handling: "none", run_worker_first: overflowRoutes(overflowRels, toolkitRoutes(toolkit)) } },
  };
}

// Replaces the Worker's code and settings, keeping its static files.
// token: from apiToken() (cloudflare.js); patch: from keepAssetsPatch()
export async function deployKeepingAssets({ token, accountId, slug, patch }) {
  const route = (template) => template.replace("{account_id}", accountId).replace("{worker_id}", encodeURIComponent(slug));

  const found = await workersApi(token, "GET", route(WORKERS_API.worker));
  if (found.status === 404) throw new Error(`This Cloudflare account has no Worker named "${slug}".`);
  if (!found.ok) throw apiError("Could not read the Worker", found);

  const res = await workersApi(token, "PATCH", `${route(WORKERS_API.patchLatest)}?deploy=true`, patch);
  if (!res.ok) throw apiError("Could not update the Worker", res);
}

async function workersApi(token, method, route, body) {
  const headers = { authorization: `Bearer ${token}` };
  if (body) headers["content-type"] = "application/merge-patch+json";
  const res = await fetch(`${WORKERS_API.base}${route}`, { method, headers, body: body && JSON.stringify(body) });
  // Cloudflare announces API removals with these headers.
  const notice = ["deprecation", "sunset"].map((h) => res.headers.get(h) && `${h}: ${res.headers.get(h)}`).filter(Boolean);
  if (notice.length) log.warn(`Cloudflare marks an API this command uses as going away (${notice.join(", ")}). ${apiNote()}`);
  const json = await res.json().catch(() => ({}));
  for (const m of json.messages || []) log.info(`Cloudflare: ${m.message || JSON.stringify(m)}`);
  return { status: res.status, ok: res.ok && json.success !== false, errors: json.errors || [] };
}

function apiError(what, res) {
  const reason = res.errors.map((e) => `${e.message}${e.code ? ` [code: ${e.code}]` : ""}`).join("; ") || `HTTP ${res.status}`;
  return new Error(`${what}: ${reason}\n${apiNote()}`);
}

function apiNote() {
  return (
    `This command was checked against the Cloudflare API on ${WORKERS_API.checked}; ` +
    "if Cloudflare changed it since, deploy from the game folder instead and report it at https://github.com/Kokoroou/rpgmaker-web-toolkit/issues"
  );
}

//---------------------------------------------------------------------------
// Checking the requests above against Cloudflare's OpenAPI schema
//---------------------------------------------------------------------------

// openapi: the parsed schema -> problems (empty when everything still matches)
export function checkWorkersApi(openapi) {
  const problems = [];
  const deref = (node, seen = 0) => {
    if (!node || typeof node !== "object" || !node.$ref || seen > 20) return node;
    let target = openapi;
    for (const key of node.$ref.replace(/^#\//, "").split("/")) target = target?.[key];
    return deref(target, seen + 1);
  };
  const props = (schema) => {
    schema = deref(schema) || {};
    const out = { ...(schema.properties || {}) };
    for (const part of schema.allOf || []) Object.assign(out, props(part));
    return out;
  };
  const need = (ok, what) => {
    if (!ok) problems.push(what);
    return ok;
  };

  const paths = openapi.paths || {};
  need(paths[WORKERS_API.worker]?.get, `GET ${WORKERS_API.worker} is gone`);
  const patch = paths[WORKERS_API.patchLatest]?.patch;
  if (!need(patch, `PATCH ${WORKERS_API.patchLatest} is gone`)) return problems;

  const params = (patch.parameters || []).map(deref);
  need(params.some((p) => p.name === "deploy" && p.in === "query"), "the version patch has no ?deploy= any more");
  need(/omitted fields are inherited/i.test(patch.description || ""), "the version patch no longer says omitted fields are inherited (static files may not carry over)");
  const body = deref(patch.requestBody)?.content?.["application/merge-patch+json"];
  if (!need(body, "the version patch no longer takes application/merge-patch+json")) return problems;

  const fields = props(body.schema);
  for (const key of ["main_module", "compatibility_date", "bindings", "modules", "assets"]) need(fields[key], `the version patch has no "${key}" field`);
  const config = props(props(fields.assets).config);
  for (const key of ["not_found_handling", "run_worker_first"]) need(config[key], `assets.config has no "${key}"`);
  const moduleFields = props(deref(fields.modules)?.items);
  for (const key of ["name", "content_type", "content_base64"]) need(moduleFields[key], `modules[] has no "${key}"`);

  const schemas = openapi.components?.schemas || {};
  const binding = (kind, field) => need(props(schemas[`workers_binding_kind_${kind}`])[field], `the ${kind} binding has no "${field}"`);
  binding("plain_text", "text");
  binding("r2_bucket", "bucket_name");
  binding("assets", "type");
  return problems;
}
